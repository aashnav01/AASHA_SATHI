// Utility functions
export function getTasksByCategory(category: NRHMTask['category']): NRHMTask[] {
  return NRHM_TASKS.filter(t => t.category === category);
}

export function getCategoryMetadata(categoryId: string) {
  return NRHM_CATEGORIES.find(c => c.id === categoryId);
}

export function getTotalMonthlyIncentive(): number {
  return NRHM_TASKS.reduce((sum, t) => sum + t.incentive_amount, 0);
}

export function getIncentiveByCategory(category: NRHMTask['category']): number {
  return getTasksByCategory(category).reduce((sum, t) => sum + t.incentive_amount, 0);
}
